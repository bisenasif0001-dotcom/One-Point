const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const data = new Map([['opds_analytics_logs', '[{"phone":"private fixture"}]']]);
const listeners = {};
const context = { window: {}, innerWidth: 390, Date, URL, location: { origin: 'https://example.test', href: 'https://example.test/checkout.html?email=private@example.test' }, document: { addEventListener: (name, fn) => listeners[name] = fn }, localStorage: { getItem: key => data.get(key), setItem: (key,value) => data.set(key,value), removeItem: key => data.delete(key) }, fetch: () => { throw new Error('Metrics must not send network requests'); } };
vm.runInNewContext(fs.readFileSync('assets/pilot-metrics.js','utf8'), context);
assert.equal(data.has('opds_analytics_logs'), false, 'Remove legacy personal payloads');
const metrics = context.window.OPDSPilotMetrics;
metrics.track('checkout_started', { once: true, email: 'private@example.test', orderId: 'private-order', url: 'private-url' });
metrics.track('checkout_started', { once: true });
metrics.track('arbitrary_private_event');
metrics.track('upload_error', { fileName: 'private.pdf' });
const raw = data.get('opds_pilot_counters_v1');
assert(!/private|email|orderId|fileName|url|https/.test(raw), 'No raw identifiers or URLs');
const today = new Date().toISOString().slice(0,10);
assert.equal(JSON.parse(raw)[today]['checkout_started:phone'], 1, 'Once-per-page guard');
assert.equal(JSON.parse(raw)[today]['upload_error:phone'], 1);
context.localStorage.setItem = () => { throw new Error('Storage blocked'); };
assert.doesNotThrow(() => metrics.track('checkout_error'), 'Unavailable storage cannot block checkout');
fs.writeFileSync('artifacts/pilot-metrics-test.json', JSON.stringify({ result:'PASS', checks:['legacy raw log removed','no identifiers/URLs/raw parameters stored','fixed events only','once per page','no network collector','blocked storage does not throw'], scope:'local diagnostic counters, not production conversion analytics' },null,2));
console.log('PASS privacy-bounded local pilot counters');
